// =========================================================================
// FAST HIGH-PERFORMANCE BITMAP BLITTER (Host & Arduino Compatible)
// =========================================================================
static inline void mochi_blit_mono(uint8_t* buffer, int buf_w, int buf_h, int dst_x, int dst_y, int w, int h, const uint8_t* bmp, bool invert = false) {
    if (!buffer || !bmp) return;
    int row_bytes = (w + 7) / 8;
    for (int y = 0; y < h; y++) {
        int py = dst_y + y;
        if (py < 0 || py >= buf_h) continue;
        for (int x = 0; x < w; x++) {
            int px = dst_x + x;
            if (px < 0 || px >= buf_w) continue;
            int byte_idx = y * row_bytes + (x / 8);
            int bit_idx = 7 - (x % 8);
            bool pixel = (bmp[byte_idx] >> bit_idx) & 1;
            if (invert) pixel = !pixel;
            if (pixel) {
                buffer[py * (buf_w / 8) + (px / 8)] |= (1 << (7 - (px % 8)));
            }
        }
    }
}

